/*
 * Subtitle format dispatch tests: ASS parsing (override tags, drawing cues, layered
 * duplicates, Format: field order), VTT normalization, format sniffing, overlay-text
 * cleanup, and cue shifting.
 *
 * Run: bun utils/yomifin/subtitleParse.test.ts (or ./scripts/yomifin-test.sh)
 */
import assert from "node:assert/strict";
import { parseSrt } from "./srt";
import {
  cleanSubtitleOverlayText,
  detectSubtitleFormat,
  parseAss,
  parseSubtitleText,
  shiftCues,
} from "./subtitleParse";

let passed = 0;
function test(name: string, fn: () => void) {
  fn();
  passed++;
  console.log(`  ✓ ${name}`);
}

const ASS_SAMPLE = `[Script Info]
; Script generated by Aegisub
Title: sample
ScriptType: v4.00+

[V4+ Styles]
Format: Name, Fontname, Fontsize
Style: Default,Arial,48

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:01.50,0:00:03.20,Default,,0,0,0,,{\\i1}こんにちは{\\i0}、世界
Comment: 0,0:00:02.00,0:00:04.00,Default,,0,0,0,,編集メモ（無視）
Dialogue: 0,0:00:05.00,0:00:07.00,Default,,0,0,0,,二行目です\\Nそして続き
Dialogue: 1,0:00:05.00,0:00:07.00,Default,,0,0,0,,二行目です\\Nそして続き
Dialogue: 0,0:00:08.00,0:00:09.00,Sign,,0,0,0,,{\\p1}m 0 0 l 100 0 100 100{\\p0}
Dialogue: 0,0:00:10.00,0:00:12.00,Default,,0,0,0,,カンマ,を,含む台詞
`;

test("parseAss: dialogue extracted, tags stripped, \\N → newline", () => {
  const cues = parseAss(ASS_SAMPLE);
  assert.equal(cues.length, 3);
  assert.equal(cues[0].text, "こんにちは、世界");
  assert.equal(cues[0].startMs, 1500);
  assert.equal(cues[0].endMs, 3200);
  assert.equal(cues[1].text, "二行目です\nそして続き");
});

test("parseAss: comments skipped, drawing cues dropped, layered dupes deduped", () => {
  const cues = parseAss(ASS_SAMPLE);
  // Comment: line and the {\p1} sign are gone; the layer-1 duplicate collapsed.
  assert.equal(cues.filter((c) => c.text.includes("編集メモ")).length, 0);
  assert.equal(cues.filter((c) => c.text.includes("m 0 0")).length, 0);
  assert.equal(
    cues.filter((c) => c.text === "二行目です\nそして続き").length,
    1,
  );
});

test("parseAss: Text field keeps embedded commas (last-field split)", () => {
  const cues = parseAss(ASS_SAMPLE);
  assert.equal(cues[2].text, "カンマ,を,含む台詞");
});

test("parseAss: custom Format field order respected", () => {
  const custom = `[Events]
Format: Start, End, Text
Dialogue: 0:00:01.00,0:00:02.00,順序が違う
`;
  const cues = parseAss(custom);
  assert.equal(cues.length, 1);
  assert.equal(cues[0].text, "順序が違う");
  assert.equal(cues[0].startMs, 1000);
});

test("parseAss: CRLF + BOM tolerated, sorted by start", () => {
  const crlf = `\uFEFF[Events]\r\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\r\nDialogue: 0,0:00:09.00,0:00:10.00,D,,0,0,0,,あと\r\nDialogue: 0,0:00:01.00,0:00:02.00,D,,0,0,0,,さき\r\n`;
  const cues = parseAss(crlf);
  assert.equal(cues.length, 2);
  assert.equal(cues[0].text, "さき");
  assert.equal(cues[1].text, "あと");
});

test("detectSubtitleFormat: extension wins, then content sniff", () => {
  assert.equal(detectSubtitleFormat("whatever", "ep01.ASS"), "ass");
  assert.equal(detectSubtitleFormat("whatever", "ep01.srt"), "srt");
  assert.equal(
    detectSubtitleFormat("WEBVTT\n\n00:01.000 --> 00:02.000\nhi"),
    "vtt",
  );
  assert.equal(detectSubtitleFormat(ASS_SAMPLE), "ass");
  assert.equal(
    detectSubtitleFormat("1\n00:00:01,000 --> 00:00:02,000\nこんにちは\n"),
    "srt",
  );
});

test("parseSubtitleText: VTT header/id lines handled, MM:SS.mmm gets hours", () => {
  const vtt = `WEBVTT - some header

NOTE this is a comment block

intro-cue
00:01.000 --> 00:02.500 align:middle
こんにちは <b>世界</b>

2
00:01:00.000 --> 00:01:02.000
フルタイムスタンプ
`;
  const cues = parseSubtitleText(vtt, "sample.vtt");
  assert.equal(cues.length, 2);
  assert.equal(cues[0].startMs, 1000);
  assert.equal(cues[0].endMs, 2500);
  assert.equal(cues[0].text, "こんにちは 世界");
  assert.equal(cues[1].startMs, 60_000);
});

test("parseSrt: still parses plain SRT after the timing-line-scan change", () => {
  const srt = `1
00:00:01,000 --> 00:00:02,000
こんにちは

00:00:03,000 --> 00:00:04,000
番号なしブロック
`;
  const cues = parseSrt(srt);
  assert.equal(cues.length, 2);
  assert.equal(cues[0].index, 1);
  assert.equal(cues[1].text, "番号なしブロック");
});

test("cleanSubtitleOverlayText: strips leaked override blobs, keeps real braces", () => {
  assert.equal(
    cleanSubtitleOverlayText("{\\an8}上のセリフ{\\i0}です"),
    "上のセリフです",
  );
  assert.equal(
    cleanSubtitleOverlayText("集合{1, 2}を考える"),
    "集合{1, 2}を考える",
  );
  assert.equal(cleanSubtitleOverlayText(""), "");
});

test("shiftCues: offsets both ends; 0 is identity (same array)", () => {
  const cues = parseAss(ASS_SAMPLE);
  const shifted = shiftCues(cues, -500);
  assert.equal(shifted[0].startMs, 1000);
  assert.equal(shifted[0].endMs, 2700);
  assert.equal(cues[0].startMs, 1500); // original untouched
  assert.equal(shiftCues(cues, 0), cues);
});

console.log(`\nsubtitleParse: all ${passed} tests passed`);
